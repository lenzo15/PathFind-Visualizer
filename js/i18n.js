  function resolveLocale(saved, languages = []) {
    if (Object.hasOwn(messages, saved)) return saved;
    for (const language of languages) {
      if (/^zh(?:-|$)/i.test(language)) return "zh-CN";
      if (/^en(?:-|$)/i.test(language)) return "en";
    }
    return "zh-CN";
  }

  function translate(key, params = {}, language = "zh-CN") {
    const dictionary = Object.hasOwn(messages, language) ? messages[language] : messages["zh-CN"];
    const template = Object.hasOwn(dictionary, key) ? dictionary[key]
      : Object.hasOwn(messages["zh-CN"], key) ? messages["zh-CN"][key] : String(key);
    return template.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
  }

  function createLocalizer({ storage, languages = [] } = {}) {
    let saved;
    try { saved = storage && storage.getItem(STORAGE_KEY); } catch (_) { /* Storage may be blocked, including file://. */ }
    let language = resolveLocale(saved, languages);
    return {
      get language() { return language; },
      t(key, params) { return translate(key, params, language); },
      setLanguage(next) {
        if (!Object.hasOwn(messages, next)) return false;
        language = next;
        try { if (storage) storage.setItem(STORAGE_KEY, next); } catch (_) { /* Switching still works without storage. */ }
        return true;
      },
      apply(document) {
        document.documentElement.lang = language;
        document.querySelectorAll("[data-i18n]").forEach(element => {
          element.textContent = translate(element.dataset.i18n, {}, language);
        });
        for (const attribute of ["title", "aria-label", "placeholder", "content"]) {
          document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
            element.setAttribute(attribute, translate(element.getAttribute(`data-i18n-${attribute}`), {}, language));
          });
        }
      }
    };
  }

  return Object.freeze({ STORAGE_KEY, messages, resolveLocale, translate, createLocalizer });
